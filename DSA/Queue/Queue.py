# Short definition:

# A queue is a linear data structure that follows FIFO (First In, First Out).

# Real-world applications:

# 🏦 Bank customer line
# 🖨️ Printer job queue
# 🎫 Ticket booking system
# 🌐 Network data packets
# 🖥️ CPU task scheduling

# Remember:
# Queue → FIFO → First comes, first goes.


queue = []

queue.append(10)
queue.append(20)
queue.append(30)

print(queue)
print(queue.pop(0))
print(queue)